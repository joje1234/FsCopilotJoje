import { copyFileSync, existsSync, mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from 'fs';
import { join, resolve } from 'path';
import { fileURLToPath } from 'url';
import { bundle } from './build-ui.mjs';

const root = fileURLToPath(new URL('../', import.meta.url));
const arg = process.argv.indexOf('--wasm');
if (arg < 0 || !process.argv[arg + 1]) throw new Error('Usage: node scripts/package.mjs --wasm <built FsCopilotControls.wasm>');
const wasm = resolve(process.argv[arg + 1]);
if (!existsSync(wasm) || readFileSync(wasm).subarray(0, 8).compare(Buffer.from([0, 97, 115, 109, 1, 0, 0, 0])) !== 0)
    throw new Error('A compiled WebAssembly module is required; no UI-only simulator package will be created.');
const wasmModule = new WebAssembly.Module(readFileSync(wasm));
const exported = WebAssembly.Module.exports(wasmModule).filter(item => item.kind === 'function').map(item => item.name);
for (const callback of ['module_init', 'module_deinit', 'Update_StandAlone']) {
    if (!exported.includes(callback)) throw new Error(`WASM module does not export ${callback}; refusing to package it.`);
}

const outputArg = process.argv.indexOf('--output');
if (outputArg >= 0 && !process.argv[outputArg + 1]) throw new Error('--output requires a directory.');
const output = outputArg >= 0 ? resolve(process.argv[outputArg + 1]) : resolve(root, '../artifacts/efb-control-test/fscopilot-controls-test');
const ui = join(output, 'html_ui/efb_ui/efb_apps/FsCopilotControls');
mkdirSync(join(ui, 'Assets'), { recursive: true });
mkdirSync(join(output, 'modules'), { recursive: true });
writeFileSync(join(ui, 'FsCopilotControls.js'), '// Generated by scripts/build-ui.mjs.\n' + bundle);
copyFileSync(join(root, 'PackageSources/FsCopilotControls/Assets/icon.svg'), join(ui, 'Assets/icon.svg'));
copyFileSync(wasm, join(output, 'modules/FsCopilotControls.wasm'));
copyFileSync(join(root, 'THIRD_PARTY_NOTICES.txt'), join(output, 'THIRD_PARTY_NOTICES.txt'));
copyFileSync(join(root, '../LICENSE'), join(output, 'LICENSE.txt'));
writeFileSync(join(output, 'manifest.json'), JSON.stringify({
    dependencies: [], content_type: 'MISC', title: 'FS Copilot Controls Test', manufacturer: '', creator: 'FS Copilot',
    package_version: '0.1.0', minimum_game_version: '1.0.0', release_notes: { neutral: { LastUpdate: '', OlderHistory: '' } }
}, null, 2));
const content = [];
function walk(folder) {
    for (const name of readdirSync(folder).sort()) {
        const file = join(folder, name);
        const stat = statSync(file);
        if (stat.isDirectory()) walk(file);
        else if (name !== 'layout.json') {
            content.push({ path: file.slice(output.length + 1).replace(/\\/g, '/'), size: stat.size,
                date: Number(BigInt(Math.trunc(stat.mtimeMs)) * 10000n + 116444736000000000n) });
        }
    }
}
walk(output);
writeFileSync(join(output, 'layout.json'), JSON.stringify({ content }, null, 2));
console.log('Community package: ' + output);
